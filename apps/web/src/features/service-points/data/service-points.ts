export type ServicePointStatus = 'active' | 'inactive'

export interface ServicePointRecord {
  id: string
  /** Short human-entered identifier shown in the table (e.g. SP-JKT-001). */
  code: string
  name: string
  /** Owning service point; null marks a top-level (root) entry. */
  parentId: string | null
  region: string | null
  address: string | null
  phone: string | null
  email: string | null
  latitude: number | null
  longitude: number | null
  status: ServicePointStatus
  notes: string | null
  /**
   * Display-only count. Real numbers will come from the future Service Point
   * Assignment module (user ⇄ assignment ⇄ service point) — same for leader
   * and PIC, which is why neither is stored on this master record.
   */
  assignedUsers: number
  /** ISO date (yyyy-mm-dd) — string so SSR and client render identically. */
  createdAt: string
}

